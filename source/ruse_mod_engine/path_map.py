# ── ObjRef class translation helper ──────────────────────────────────────────

def translate_everything_cpp_set(value):
    """Translate ObjRef class indices in an everything.cpp set field value.

    Public wrapper for use in external tools (e.g. verify_rmod_translation).
    """
    return _translate_objref_classes(value)


def _compat_cls_to_public(compat_cls):
    """Translate a compat everything.cpp class index to the NEW-public class index.

    compat -> OLD-public (_COMPAT_CLS_TO_PUBLIC; identity for 0-188) then
    OLD-public -> NEW-public (-1 above the removed class 220).  Falls back to the
    OLD-public value if the v23660935 shift maps it to the one removed class
    (mirrors the lenient inst handling — the change is left for apply-time to
    skip rather than corrupting the value here)."""
    oldpub = _COMPAT_CLS_TO_PUBLIC.get(compat_cls, compat_cls)
    shifted = _oldpub_to_newpub_everything_cls(oldpub)
    return oldpub if shifted is None else shifted


def _translate_objref_classes(value):
    """Recursively translate ObjRef class/inst indices in a set field value.

    Handles three ObjRef forms:
    - Raw {"inst": N, "class": C}: translates both inst (>= 48888) and class (>= 189)
    - local_id {"local_id": "inst_N", "class": C}: translates class only
      (inst is resolved at apply time via create_map, but class must be pre-translated)
    - stable_ref {"stable_ref": ..., "class": C}: left unchanged
      (class is overridden at apply time from the live NDF instance)
    """
    if isinstance(value, dict):
        if "inst" in value and "class" in value:
            new_cls  = _compat_cls_to_public(value["class"])
            translated = translate_everything_cpp_index(value["inst"])
            new_inst = value["inst"] if translated is None else translated
            if new_cls == value["class"] and new_inst == value["inst"]:
                return value
            return {"inst": new_inst, "class": new_cls}
        if "local_id" in value and "class" in value:
            new_cls = _compat_cls_to_public(value["class"])
            if new_cls == value["class"]:
                return value
            return {**value, "class": new_cls}
        return {k: _translate_objref_classes(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_translate_objref_classes(item) for item in value]
    return value


# ── Public API ────────────────────────────────────────────────────────────────

def is_map_chain_path(ndf_path: str) -> bool:
    """Return True if this NDF path is inside the launchermap chain (version-specific)."""
    p = ndf_path.replace("\\", "/").lower()
    return "/launchermap/" in p


def translate_ndf_path(ndf_path: str) -> str:
    """
    Translate a Compat NDF path to its Updated equivalent.

    Core NDF files (no launchermap component) are returned unchanged.
    Paths that already use the Updated chain prefix (pre-converted rmods) are
    returned as-is.
    Paths that start with the known Compat terminal chain prefix are translated.
    Paths at intermediate chain depths (not yet used by any mod) are returned
    unchanged with a warning printed; add support as mods require it.
    """
    p = ndf_path.replace("\\", "/")
    p_lower = p.lower()

    if not is_map_chain_path(p_lower):
        return ndf_path  # core file — no translation needed

    # Already translated (e.g. pre-converted public rmod) — return as-is
    if p_lower.startswith(_UPDATED_CHAIN_PREFIX.lower()):
        return p

    compat_lower = _COMPAT_CHAIN_PREFIX.lower()
    if p_lower.startswith(compat_lower):
        suffix = p[len(_COMPAT_CHAIN_PREFIX):]
        for old, new in _INNER_SUBS:
            suffix = suffix.replace(old, new)
        return _UPDATED_CHAIN_PREFIX + suffix

    # Intermediate-depth compat path — not yet mapped
    print(f"[path_map] WARNING: no translation for intermediate chain path: {ndf_path[:80]}...")
    return ndf_path


def is_chqlmapinfo_ndf(ndf_path: str) -> bool:
    """Return True if the NDF path targets chqlmapinfo.cpp.gladndfbin."""
    return "chqlmapinfo.cpp.gladndfbin" in ndf_path.replace("\\", "/").lower()


def is_mapinfo_cpp_ndf(ndf_path: str) -> bool:
    """Return True if the NDF path targets mapinfo.cpp.gladndfbin."""
    p = ndf_path.replace("\\", "/").lower()
    return p.endswith("mapinfo.cpp.gladndfbin")


def is_everything_cpp_ndf(ndf_path: str) -> bool:
    """Return True if the NDF path targets everything.cpp.gladndfbin (not debuginfo)."""
    p = ndf_path.replace("\\", "/").lower()
    return (p.endswith("everything.cpp.gladndfbin")
            and "debuginfo" not in p)


def is_globals_cpp_ndf(ndf_path: str) -> bool:
    """Return True if the NDF path targets globals.cpp.gladndfbin."""
    return ndf_path.replace("\\", "/").lower().endswith("globals.cpp.gladndfbin")


def translate_index(table: str, og_index: int) -> int:
    """Translate a chqlmapinfo global instance index from OG to Updated.

    Returns the Updated index, or og_index unchanged if not in the lookup table.
    """
    t = table.lower()
    if t == "tmaploadinfo":
        return _ML_OG_TO_UPD.get(og_index, og_index)
    if t == "tuiresourcetexture":
        return _TX_OG_TO_UPD.get(og_index, og_index)
    return og_index


def translate_everything_cpp_index(og_index: int):
    """Translate a compat everything.cpp global instance index to the (NEW-)public index.

    Two stages: compat -> OLD-public (the verified _COMPAT_* tables), then
    OLD-public -> NEW-public (the v23660935 -1-above-46753 shift).

    Returns the translated int index, or None if the instance has no NEW-public
    equivalent (removed in the remaster, e.g. Uplay-specific, or removed by the
    v23660935 update).  Callers must check for None and skip such changes.
    """
    if og_index in _COMPAT_EVERYTHING_IDX_SPECIFIC:
        oldpub = _COMPAT_EVERYTHING_IDX_SPECIFIC[og_index]
    elif og_index >= _EVERYTHING_CPP_OFFSET_THRESHOLD:
        oldpub = og_index + _EVERYTHING_CPP_OFFSET
    else:
        oldpub = og_index
    return _oldpub_to_newpub_everything_inst(oldpub)


def translate_ia_common_path(path: str) -> str:
    """Translate a compat IA_Common.dat internal path to the public format.

    The prefix changed from genpython/100000/ (compat PC/1360/) to
    genpython/10000/ (public PC/190852/).  Map names are unchanged.
    """
    p = path.replace("\\", "/")
    if p.lower().startswith("genpython/100000/"):
        return "genpython/10000/" + p[len("genpython/100000/"):]
    return p


def translate_loc_path(path: str) -> str:
    """Translate a ZZ_Win.dat localization (.dic) internal path from compat to public.

    The per-language folder changed: compat `…/localisation/generated/<lang>/…` becomes public
    `…/localisation/translations/<lang>/…`.  The `dev/` default-language path is identical in both
    builds and is left unchanged."""
    p = path.replace("\\", "/")
    marker = "/localisation/generated/"
    idx = p.lower().find(marker)
    if idx >= 0:
        return p[:idx] + "/localisation/translations/" + p[idx + len(marker):]
    return p


def translate_datamap_path(path: str) -> str:
    """Translate a DataMap_Win.dat internal path from Compat to Updated format."""
    p = path.replace("\\", "/")
    p_lower = p.lower()
    for old, new in _DATAMAP_SUBS:
        idx = p_lower.find(old)
        if idx >= 0:
            p = p[:idx] + new + p[idx + len(old):]
            p_lower = p.lower()
    return p


def translate_rmod_data(rmod_data: dict) -> dict:
    """
    Return a deep copy of rmod_data with all paths and indices translated
    from compat (PC/99, PC/1360) to public (PC/190852) format.

    Translations applied:
    - dat paths: PC/99/ or PC/1360/ → PC/190852/
    - ndf paths: launchermap chain prefix substitution (core files unchanged)
    - everything.cpp _index/ObjRef: compat→old-public tables, then the v23660935
      -1-above-46753 (inst) / -1-above-220 (class) shift to NEW-public
    - mapinfo.cpp _index: TMapLoadInfo / TUIResourceTexture index tables applied
    - IA_Common.dat file paths: genpython/100000/ → genpython/10000/
    """
    import copy
    out = copy.deepcopy(rmod_data)
    for patch in out.get("patches", []):
        # ── DAT path ──
        dat = patch.get("dat", "")
        if dat:
            filename = dat.replace("\\", "/").split("/")[-1]
            patch["dat"] = f"PC/190852/{filename}"

        # ── NDF path ──
        ndf = patch.get("ndf", "")
        if ndf:
            patch["ndf"] = translate_ndf_path(ndf)
            ndf = patch["ndf"]

        # ── Per-change translations ──
        is_everything = is_everything_cpp_ndf(ndf)
        is_mapinfo    = is_mapinfo_cpp_ndf(ndf)
        is_globals    = is_globals_cpp_ndf(ndf)
        kept_changes = []
        for change in patch.get("changes", []):
            match = change.get("match", {})
            skip = False

            # _index translation
            if "_index" in match:
                og_idx = int(match["_index"])
                new_idx = og_idx
                if is_everything:
                    new_idx = translate_everything_cpp_index(og_idx)
                    if new_idx is None:
                        # Target instance removed from public (e.g. Uplay-specific)
                        skip = True
                    elif new_idx != og_idx:
                        match["_index"] = str(new_idx)
                elif is_mapinfo:
                    new_idx = translate_index(change.get("table", ""), og_idx)
                    if new_idx != og_idx:
                        match["_index"] = str(new_idx)
                elif is_globals:
                    new_idx = _GLOBALS_CPP_IDX_REMAP.get(og_idx, og_idx)
                    if new_idx != og_idx:
                        match["_index"] = str(new_idx)

            if skip:
                continue

            # ObjRef class index translation in set values (everything.cpp only)
            if is_everything and change.get("set"):
                change["set"] = _translate_objref_classes(change["set"])

            # Strip Uplay-only properties that don't exist in public
            if change.get("set"):
                tbl = change.get("table", "")
                s = change["set"]
                if is_everything and tbl == "TPawnSocleList" and "SocleMeshListUplay" in s:
                    s = {k: v for k, v in s.items() if k != "SocleMeshListUplay"}
                    change["set"] = s
                if is_globals and tbl == "TMultiMapInfo" and "NotDispoInBattle" in s:
                    s = {k: v for k, v in s.items() if k != "NotDispoInBattle"}
                    change["set"] = s

            kept_changes.append(change)
        patch["changes"] = kept_changes

    # ── file_patches: DAT paths + IA_Common / DataMap internal paths ──
    for fg in out.get("file_patches", []):
        dat = fg.get("dat", "")
        if dat:
            filename = dat.replace("\\", "/").split("/")[-1]
            fg["dat"] = f"PC/190852/{filename}"
            fname_lower = filename.lower()
            is_ia = fname_lower == "ia_common.dat"
            is_datamap = "datamap" in fname_lower
        else:
            is_ia = False
            is_datamap = False

        if is_ia:
            for fp in fg.get("files", []):
                p = fp.get("path", "")
                if p:
                    fp["path"] = translate_ia_common_path(p)

        if is_datamap:
            for fp in fg.get("files", []):
                p = fp.get("path", "")
                if p:
                    fp["path"] = translate_datamap_path(p)

    # ── loc_patches: DAT path + .dic path (compat 'generated/<lang>' → public 'translations/<lang>') ──
    for lg in out.get("loc_patches", []):
        dat = lg.get("dat", "")
        if dat:
            filename = dat.replace("\\", "/").split("/")[-1]
            lg["dat"] = f"PC/190852/{filename}"
        dic = lg.get("dic", "")
        if dic:
            lg["dic"] = translate_loc_path(dic)

    # ── sdb_patches: DAT path + datasmap internal path (mapinfo.win) ──
    for sg in out.get("sdb_patches", []):
        dat = sg.get("dat", "")
        if dat:
            filename = dat.replace("\\", "/").split("/")[-1]
            sg["dat"] = f"PC/190852/{filename}"
        win = sg.get("win", "")
        if win:
            sg["win"] = translate_datamap_path(win)

    return out
