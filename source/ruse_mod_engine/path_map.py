# ── old-public (v23409545) → new-public (v23660935) everything.cpp shift ──────
# The v23660935 game update removed exactly one class from everything.cpp,
# TIntuifaceSelectionHandlerInGame (old-public class idx 220), and its single
# instance (old-public global idx 46753).  Every other class/instance keeps its
# identity, but its NUMERIC index shifts -1 if it sat above the removed slot.
# Verified by deriving the full old->new identity map from both NDFs
# (ai_unit_tests/claude/migrate_rmods_to_new_public.py).
#
# The compat translation tables above (_COMPAT_*, _GLOBALS_*, mapinfo) were all
# derived against OLD-public, so the compat->public result is post-composed with
# this shift to land on NEW-public.  globals.cpp / mapinfo.cpp layouts did NOT
# change in this update (values only), so only everything.cpp needs this layer.
_NEWPUB_EVERYTHING_INST_REMOVED = 46753
_NEWPUB_EVERYTHING_CLS_REMOVED = 220


def _oldpub_to_newpub_everything_inst(i):
    """Shift an OLD-public everything.cpp instance index to NEW-public.
    Returns None if it referenced the one removed instance (caller skips)."""
    if i is None or i == _NEWPUB_EVERYTHING_INST_REMOVED:
        return None
    return i - 1 if i > _NEWPUB_EVERYTHING_INST_REMOVED else i


def _oldpub_to_newpub_everything_cls(c):
    """Shift an OLD-public everything.cpp class index to NEW-public.
    Returns None if it referenced the one removed class (caller keeps old)."""
    if c is None or c == _NEWPUB_EVERYTHING_CLS_REMOVED:
        return None
    return c - 1 if c > _NEWPUB_EVERYTHING_CLS_REMOVED else c


